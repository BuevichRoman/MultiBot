/**
 * Разбор плановых перерывов, которые заказчик вводит при создании заказа
 * (ТЗ-001 п. 5).
 *
 * Запуск: npm run build && node tests/test_planned_breaks.js
 */

const assert = require('node:assert/strict');
const { parsePlannedBreaks } = require('../dist/src/engine/children/parsers/parsePlannedBreaks.js');

const ok = [
  ['11:00-12:00', [{ started: '11:00', ended: '12:00' }], 'один интервал'],
  ['9:30-10:00', [{ started: '09:30', ended: '10:00' }], 'час без ведущего нуля'],
  ['11:00 - 12:00', [{ started: '11:00', ended: '12:00' }], 'пробелы вокруг дефиса'],
  ['11:00–12:00', [{ started: '11:00', ended: '12:00' }], 'длинное тире'],
  [
    '11:00-12:00, 14:30-15:00',
    [{ started: '11:00', ended: '12:00' }, { started: '14:30', ended: '15:00' }],
    'два интервала через запятую',
  ],
  [
    '14:30-15:00,11:00-12:00',
    [{ started: '14:30', ended: '15:00' }, { started: '11:00', ended: '12:00' }],
    'порядок ввода сохраняется',
  ],
  ['00:00-23:59', [{ started: '00:00', ended: '23:59' }], 'границы суток'],
];

const bad = [
  ['', 'пустая строка'],
  ['завтра', 'произвольный текст'],
  ['11:00', 'только начало без окончания'],
  ['11-12', 'без минут'],
  ['25:00-26:00', 'часы больше 23'],
  ['11:70-12:00', 'минуты больше 59'],
  ['12:00-11:00', 'обратный интервал'],
  ['11:00-11:00', 'нулевая длительность'],
  ['23:00-01:00', 'через полночь'],
  ['11:00-13:00, 12:00-14:00', 'пересекающиеся интервалы'],
  ['11:00-12:00, мусор', 'один из интервалов не разобран'],
];

for (const [input, expected, name] of ok) {
  assert.deepEqual(parsePlannedBreaks(input), expected, `должно разбираться: ${name} (${input})`);
}

for (const [input, name] of bad) {
  assert.equal(parsePlannedBreaks(input), undefined, `должно отклоняться: ${name} (${input})`);
}

console.log(`Принято корректных вариантов: ${ok.length}`);
console.log(`Отклонено некорректных: ${bad.length}`);
console.log('\nВсе проверки пройдены.');
